import uuid, json
from kilib import flattened, pins, dump, prop
import design

G = 2.54
def snap(v): return round(round(v / G) * G, 4)
def U(): return str(uuid.uuid4())

ROOT = str(uuid.UUID(int=0x1))  # deterministic root uuid
ROOT = '7f1d6c58-0000-4000-8000-000000000001'
PROJECT = 'impedance_afe'

libsyms = {}
out = []
pinmap = {}   # ref -> {pin: (x,y)} for reference
sym_uuid = {}
PTS = {}

def label(net, x, y, ang):
    just = {0: 'left', 90: 'left', 180: 'right', 270: 'right'}[ang]
    return f'(label "{net}" (at {x} {y} {ang}) (fields_autoplaced) (effects (font (size 1.27 1.27)) (justify {just} bottom)) (uuid {U()}))'

for p in design.parts:
    lib_id = p['sym']
    if lib_id not in libsyms:
        l, s = lib_id.split(':')
        libsyms[lib_id] = flattened(l, s)
    sn = libsyms[lib_id]
    X, Y = snap(p['at'][0]), snap(p['at'][1])
    uid = str(uuid.uuid5(uuid.NAMESPACE_DNS, 'afe-sym-' + p['ref'])); sym_uuid[p['ref']] = uid
    is_pwr = p['ref'].startswith('#')
    fp = p['fp'] if p['fp'] else ''
    props = [
        f'(property "Reference" "{p["ref"]}" (at {X+3.81} {Y-6.35} 0) (effects (font (size 1.27 1.27)) (justify left){" hide" if is_pwr else ""}))',
        f'(property "Value" "{p["value"]}" (at {X+3.81} {Y-4.45} 0) (effects (font (size 1.27 1.27)) (justify left)))',
        f'(property "Footprint" "{fp}" (at {X} {Y} 0) (effects (font (size 1.27 1.27)) hide))',
        f'(property "Datasheet" "" (at {X} {Y} 0) (effects (font (size 1.27 1.27)) hide))',
    ]
    if p.get('mpn'): props.append(f'(property "MPN" "{p["mpn"]}" (at {X} {Y} 0) (effects (font (size 1.27 1.27)) hide))')
    if p.get('lcsc'): props.append(f'(property "LCSC" "{p["lcsc"]}" (at {X} {Y} 0) (effects (font (size 1.27 1.27)) hide))')
    if p.get('note'): props.append(f'(property "Note" "{p["note"]}" (at {X} {Y} 0) (effects (font (size 1.27 1.27)) hide))')
    pl = pins(sn)
    pin_s = ' '.join(f'(pin "{q["number"]}" (uuid {U()}))' for q in pl)
    dnp = 'yes' if p['dnp'] else 'no'
    inbom = 'no' if is_pwr else 'yes'
    out.append(f'(symbol (lib_id "{lib_id}") (at {X} {Y} 0) (unit 1) (in_bom {inbom}) (on_board {"no" if is_pwr else "yes"}) (dnp {dnp}) (uuid {uid})\n  '
               + '\n  '.join(props) + f'\n  {pin_s}\n  (instances (project "{PROJECT}" (path "/{ROOT}" (reference "{p["ref"]}") (unit 1)))))')
    used = set()
    for q in pl:
        ex, ey = round(X + q['x'], 4), round(Y - q['y'], 4)
        net = p['nets'].get(q['number'])
        if net is None:
            out.append(f'(no_connect (at {ex} {ey}) (uuid {U()}))')
            continue
        used.add(q['number'])
        a = int(q['angle']) % 360
        dx, dy, lang = {0: (-G, 0, 180), 180: (G, 0, 0), 90: (0, G, 270), 270: (0, -G, 90)}[a]
        sx, sy = round(ex + dx, 4), round(ey + dy, 4)
        for pt in ((ex, ey), (sx, sy)):
            prev = PTS.setdefault(pt, (net, p['ref']))
            assert prev[0] == net or prev[1] == p['ref'] and prev[0] == net, ('COLLISION', pt, prev, net, p['ref'])
        out.append(f'(wire (pts (xy {ex} {ey}) (xy {sx} {sy})) (stroke (width 0) (type default)) (uuid {U()}))')
        out.append(label(net, sx, sy, lang))
    missing = set(p['nets']) - used
    assert not missing, (p['ref'], missing)

for (x, y), t in design.TEXT:
    t = t.replace('"', "'").replace('|', '\\n')
    out.append(f'(text "{t}" (at {x} {y} 0) (effects (font (size 1.8 1.8) bold) (justify left bottom)) (uuid {U()}))')

title = ('(title_block (title "Impedance / C-V / DLTS / Electrochem Analog Front End") (date "2026-11-11") (rev "A") '
         '(comment 1 "Dual TIA (diode-steered hi/lo gain), PI potentiostat, driven guard") (comment 2 "Generated by script - see design.py"))')
lib_s = '\n'.join(dump(s, 1) for s in libsyms.values())
doc = (f'(kicad_sch (version 20230121) (generator eeschema)\n (uuid {ROOT})\n (paper "A2")\n {title}\n'
       f' (lib_symbols\n{lib_s}\n )\n' + '\n'.join(out) +
       f'\n (sheet_instances (path "/" (page "1")))\n)\n')
open(f'{PROJECT}.kicad_sch', 'w').write(doc)
json.dump(sym_uuid, open('sym_uuid.json', 'w'), indent=0)
print('parts', len(design.parts))
